// pack-barrel.ts — regenerate api/src/lib/trades/packs/index.ts from the pack files on disk.
// Usage: npm run pack:barrel
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPO_ROOT } from '../lib/trades/packs/catalog-scan.js';

export const PACKS_DIR = join(REPO_ROOT, 'api', 'src', 'lib', 'trades', 'packs');
const INFRA = new Set(['schema', 'sources', 'runtime', 'guards', 'index', 'catalog-scan', 'catalog-manifest']);

export function packFileKeys(): string[] {
  return readdirSync(PACKS_DIR)
    .filter((f) => f.endsWith('.ts') && !INFRA.has(f.slice(0, -3)))
    .map((f) => f.slice(0, -3))
    .sort();
}

export function renderBarrel(keys: string[]): string {
  const imports = keys.map((k) => `import p_${k} from './${k}.js';`).join('\n');
  const entries = keys.map((k) => `  ['${k}', p_${k}],`).join('\n');
  return `// GENERATED by \`npm run pack:barrel\` — do not edit by hand. One entry per pack file.
import type { TradePack } from './schema.js';
${imports}

/** [file key, pack] — the guard test checks file key === pack.key. */
export const PACK_FILES: ReadonlyArray<readonly [string, TradePack]> = [
${entries}
];

export const PACKS: ReadonlyMap<string, TradePack> = new Map(PACK_FILES.map(([, p]) => [p.key, p]));
`;
}

if (process.argv[1]?.endsWith('pack-barrel.ts')) {
  const keys = packFileKeys();
  writeFileSync(join(PACKS_DIR, 'index.ts'), renderBarrel(keys));
  console.log(`packs/index.ts: ${keys.length} packs`);
}
