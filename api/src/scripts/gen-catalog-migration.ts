// gen-catalog-migration.ts — turn pack assemblies that are not yet seeded into ONE append-only migration
// (style of 0045: sentinel tenant, is_system, source 'platform-seed', ON CONFLICT DO NOTHING, one
// provenance comment per row) + update packs/catalog-manifest.ts.
// Usage: npm run gen:catalog-migration -- --wave 01            dry run (prints SQL)
//        npm run gen:catalog-migration -- --wave 01 --apply    write prisma/migrations/NNNN_trade_pack_catalog_w01
// Cost corrections to an already-seeded code need a hand-written UPDATE migration — never edit an applied one.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PACK_FILES } from '../lib/trades/packs/index.js';
import { CATALOG_MANIFEST } from '../lib/trades/packs/catalog-manifest.js';
import { MIGRATIONS_DIR, REPO_ROOT, nextMigrationNumber, seededCatalogCodes } from '../lib/trades/packs/catalog-scan.js';
import { packBucket } from '../lib/trades/packs/guards.js';

const args = process.argv.slice(2);
const wave = args[args.indexOf('--wave') + 1];
if (!wave || args.indexOf('--wave') < 0) { console.error('usage: gen:catalog-migration -- --wave NN [--apply]'); process.exit(2); }
const apply = args.includes('--apply');

const seeded = seededCatalogCodes();
const sq = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows: string[] = [];
const manifest: Record<string, string> = { ...CATALOG_MANIFEST };
const num = nextMigrationNumber();
const name = `${num}_trade_pack_catalog_w${wave}`;

for (const [, p] of PACK_FILES) {
  for (const a of p.assemblies ?? []) {
    if (seeded.has(a.code) || a.code in CATALOG_MANIFEST) continue;
    const provs = [a.material_cost_cents, a.labor_hours_per_unit, a.equipment_cost_cents, a.waste_pct].map((x) => x.prov);
    const srcs = [...new Set(provs.flatMap((pr) => pr.src))].join(', ');
    const conf = [...new Set(provs.map((pr) => pr.confidence))].join('/');
    rows.push(`  -- ${a.code} (${p.key}@${p.pack_version}): ${srcs} — ${conf}, verified ${provs[0].last_verified}
  ('00000000-0000-0000-0000-000000000000', ${sq(packBucket(p))}, ${sq(a.code)}, ${sq(a.name)}, ${a.description ? sq(a.description) : 'NULL'}, ${sq(a.unit)}, ${sq(a.csi)}, ${a.material_cost_cents.v}, ${a.labor_hours_per_unit.v}, ${a.equipment_cost_cents.v}, ${a.waste_pct.v}, TRUE, 'platform-seed')`);
    manifest[a.code] = name;
  }
}
if (rows.length === 0) { console.log('No new pack assemblies — nothing to generate.'); process.exit(0); }

const sql = `-- ${name} — Trade Knowledge Pack catalog rows (wave ${wave}). GENERATED by gen-catalog-migration.ts.
-- System assemblies (sentinel tenant, is_system) — read-any via RLS, tenants override by (trade, code) (T-63).
-- Costs are national baselines with provenance (Doc 23 §4); 'estimate' rows are badged "tune per tenant".
INSERT INTO estimate_assemblies
  (tenant_id, trade, code, name, description, unit, csi_division, material_cost_cents, labor_hours_per_unit, equipment_cost_cents, waste_pct, is_system, source)
VALUES
${rows.join(',\n')}
ON CONFLICT (tenant_id, trade, code) WHERE deleted_at IS NULL DO NOTHING;
`;
if (!apply) { console.log(sql); console.log(`(dry run — ${rows.length} row(s); add --apply to write ${name})`); process.exit(0); }
mkdirSync(join(MIGRATIONS_DIR, name), { recursive: true });
writeFileSync(join(MIGRATIONS_DIR, name, 'migration.sql'), sql);
const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(join(REPO_ROOT, 'api/src/lib/trades/packs/catalog-manifest.ts'),
  `// GENERATED by \`npm run gen:catalog-migration -- --apply\` — do not edit by hand.
// Pack assembly code → the migration that seeds it.
export const CATALOG_MANIFEST: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 2)};
`);
console.log(`wrote prisma/migrations/${name}/migration.sql (${rows.length} rows) + catalog-manifest.ts`);
